DEST = ROOT/'results/gap-confirmation'
INPUTS = ROOT/'inputs/gap-confirmation'
ARMS = [dict(name='dense',points=65536),dict(name='canonical',points=16384),
        dict(name='phase-1',points=16384),dict(name='shuffle',points=16384)]
ENDS = [26000,30000]


def utc():
    return dt.datetime.now(dt.timezone.utc).isoformat()


def code_hashes():
    paths = ['scripts/gap_training_controls.py','scripts/gap_lr_controls.py',
             'scripts/gap_density_controls.py','scripts/gap_confirmation.py',
             'tests/test_gap_confirmation.py']
    return {**sources(),**{p:digest(ROOT/p) for p in paths}}


def same(a,b):
    if isinstance(a,torch.Tensor): return isinstance(b,torch.Tensor) and torch.equal(a,b)
    if isinstance(a,dict): return isinstance(b,dict) and a.keys()==b.keys() and all(same(a[k],b[k]) for k in a)
    if isinstance(a,(tuple,list)): return type(a)==type(b) and len(a)==len(b) and all(same(x,y) for x,y in zip(a,b))
    return a==b


def schedule(name,pair_index,updates=10000):
    if name=='dense': return torch.zeros(updates,dtype=torch.long)
    if name=='canonical': return torch.arange(updates)%4
    if name=='phase-1': return (torch.arange(updates)+1)%4
    if name=='shuffle':
        gen=torch.Generator().manual_seed(700000+pair_index)
        return torch.cat([torch.randperm(4,generator=gen) for _ in range((updates+3)//4)])[:updates]
    raise ValueError('Unfrozen arm')


def stream_hash(data,arm,order,start,end):
    h=hashlib.sha256(tensor_hash(data['points'],data['target']).encode())
    n=arm['points']; raw=[torch.arange(i*n,(i+1)*n).numpy().tobytes() for i in range(65536//n)]
    for step in range(start,end): h.update(raw[int(order[step-20000])])
    return h.hexdigest()


def setup(original):
    """Copy exact legacy parents, pools and reproduction references; no model work."""
    if (INPUTS/'inventory.json').exists(): raise RuntimeError('Inputs already exist; audit them instead of replacing')
    INPUTS.mkdir(parents=True,exist_ok=True)
    m=read(ROOT/'results/gap-sampling/batch-1/manifest.json')
    old=read(ROOT/'results/gap-sampling/batch-1/summary.json')['runs']
    inventory=[]; pairs=[]
    def copy(src,dest,expected=None):
        src=Path(src); dest.parent.mkdir(parents=True,exist_ok=True)
        sha=digest(src)
        if expected is not None and sha!=expected: raise RuntimeError(f'Legacy hash mismatch: {src}')
        shutil.copyfile(src,dest)
        if digest(dest)!=sha: raise RuntimeError('Copy hash mismatch')
        inventory.append(dict(source=str(src),path=dest.relative_to(ROOT).as_posix(),sha256=sha,bytes=dest.stat().st_size))
        return dest.relative_to(ROOT).as_posix()
    for name,sha in m['source_hashes'].items():
        if digest(ROOT/name)!=sha: raise RuntimeError(f'Copied inherited source mismatch: {name}')
    for p in m['pairs']:
        c=p['config']; key=identity(c); local=dict(config=c,sha256=p['sha256'])
        src=Path(p['checkpoint']); src=src if src.is_absolute() else original/src
        local['checkpoint']=copy(src,INPUTS/key/'parent-20000.pt',p['sha256'])
        local['pool']=copy(original/'runs/gap-sampling/batch-1'/key/'pool.pt',INPUTS/key/'pool.pt')
        local['independent']=copy(original/'runs/gap-sampling/batch-1'/key/'independent.pt',INPUTS/key/'independent.pt')
        local['historical']={}
        for name,historical_arm in [('dense','dense'),('canonical','cycle-16384')]:
            local['historical'][name]={}
            for end in ENDS:
                r=next(r for r in old if r['metadata']['config']==c and r['training']['arm']['name']==historical_arm and r['metadata']['step']==end)
                local['historical'][name][str(end)]=copy(original/Path(r['folder'])/'checkpoint.pt',INPUTS/key/f'{name}-{end}.pt',r['metadata']['checkpoint_sha256'])
        pairs.append(local)
    copy(ROOT/'results/gap-sampling/fresh-cases-reserved.json',INPUTS/'fresh-cases-reserved.json',m['fresh_cases_sha256'])
    atomic_json(INPUTS/'inventory.json',dict(created_utc=utc(),files=inventory,pairs=pairs,
        historical_manifest_sha256=digest(ROOT/'results/gap-sampling/batch-1/manifest.json')))
    atomic_json(DEST/'budget.json',dict(limit_seconds=7200,maximum_batches=3,attempts=[]))
    print('Copied and hash-verified',len(inventory),'inputs; no reserved data generated.',flush=True)


def freeze():
    inv=read(INPUTS/'inventory.json')
    for f in inv['files']:
        if digest(ROOT/f['path'])!=f['sha256']: raise RuntimeError('Input drift')
    m=read(ROOT/'results/gap-sampling/batch-1/manifest.json')
    m.update(pairs=inv['pairs'],source_hashes=code_hashes(),checkpoints=ENDS,
        created_utc=utc(),experiment='order-robustness',input_inventory_sha256=digest(INPUTS/'inventory.json'),
        reservation_path='inputs/gap-confirmation/fresh-cases-reserved.json',
        protocol=dict(batch=1,arms=ARMS,order='Rotate arm execution left by pair index modulo four; serial GPU.',
        hypothesis='Balanced 16384-point cycling is robust to phase and independently shuffled cycle order.',
        schedule='Canonical 0,1,2,3; phase1 1,2,3,0; shuffle independent CPU Generator seed700000+pairindex; all2500 permutations before training.',
        persistence='Primary gate at26k AND30k, at192 AND384 in each of all six development pairs.',
        guards='Each checkpoint mean Chamfer at each grid<=1.05xdense; mean independent gap RMSE<=1.10xdense; mean fullgap sign delta>=-0.005.',
        compute='Each candidate presentations25%dense; aggregate training<=90%dense. Evaluation/combined reported separately.',
        validity='Dense and canonical model,Adam,samplingRNG exact historical at26k and30k. Missing/nonfinite/incomplete/unresolved reference cannot qualify.',
        stopping='If any order arm or guard fails stop with all8 reservations untouched. No tuning, replacement arm, changed shuffle seed or extra batch.',
        conditional_confirmation='ONLY if gate succeeds: freeze code and first2 cases of archived reservation with seeds71-73/global_narrow, dense/canonical/static/random; keep6 other complete cases untouched.',
        budget='<=3new batches and7200seconds whole model subprocess wall including all model tests/prep/I/O/evaluations/failures; hard timeout.'))
    path=DEST/'batch-1-manifest.json'
    with path.open('x',encoding='utf-8') as f: json.dump(m,f,indent=2,allow_nan=False); f.write('\n')
    print('Frozen:',digest(path),flush=True)


def verify_manifest(m):
    if m['source_hashes']!=code_hashes(): raise RuntimeError('Frozen source drift')
    if digest(INPUTS/'inventory.json')!=m['input_inventory_sha256']: raise RuntimeError('Input inventory drift')
    for f in read(INPUTS/'inventory.json')['files']:
        if digest(ROOT/f['path'])!=f['sha256']: raise RuntimeError('Input drift')
    if digest(ROOT/m['reservation_path'])!=m['fresh_cases_sha256']: raise RuntimeError('Reservation drift')


def train(c,previous,end,folder,data,arm,order):
    folder.mkdir(parents=True,exist_ok=False)
    device=torch.device(c['device']); saved=torch.load(previous,map_location=device,weights_only=True)
    if saved['config']!=c or not 20000<=saved['step']<end<=30000: raise RuntimeError('Invalid parent')
    model=model_for(c,device); model.load_state_dict(saved['model'])
    opt=torch.optim.Adam(model.parameters(),lr=1e-4); opt.load_state_dict(saved['optimizer'])
    initial=fixed_metrics(model,data,device); n=arm['points']
    batches=[(data['points'][i:i+n].to(device),data['target'][i:i+n].to(device)) for i in range(0,65536,n)]
    start=saved['step']; history=[]; sync(device); began=time.perf_counter()
    with (folder/'training.jsonl').open('x',encoding='utf-8') as log:
        for step in range(start+1,end+1):
            for group in opt.param_groups: group['lr']=lr_at(step-20000)
            points,target=batches[int(order[step-20001])]
            opt.zero_grad(set_to_none=True); loss=full_gradient(model,points,target,16384)
            if not torch.isfinite(loss): raise RuntimeError('Nonfinite loss; partial attempt retained')
            opt.step()
            if step%100==0 or step==end:
                row=dict(step=step,lr=lr_at(step-20000),batch_mse=loss.item(),elapsed_seconds=time.perf_counter()-began)
                history.append(row); log.write(json.dumps(row)+'\n'); log.flush()
                atomic_json(folder/'progress.json',dict(completed_update=step,completed_presentations=(step-start)*n,elapsed_seconds=time.perf_counter()-began))
    sync(device); seconds=time.perf_counter()-began
    result=dict(config=c,step=end,model=model.state_dict(),optimizer=opt.state_dict(),sample_rng=saved['sample_rng'],
        schedule='cosine',origin=20000,history=history,train_seconds=seconds,arm=arm,order_sha256=tensor_hash(order))
    torch.save(result,folder/'checkpoint.pt.tmp'); (folder/'checkpoint.pt.tmp').replace(folder/'checkpoint.pt')
    atomic_json(folder/'training.json',dict(start=start,end=end,schedule='cosine',origin=20000,seconds=seconds,arm=arm,density=65536,
        batch_points=n,chunk_size=16384,point_presentations=(end-start)*n,parent_sha256=digest(previous),
        stream_sha256=stream_hash(data,arm,order,start,end),order_sha256=tensor_hash(order),pool_sha256=tensor_hash(data['points'],data['target']),
        sample_rng_sha256=tensor_hash(saved['sample_rng']),initial_sample_rng_sha256=tensor_hash(saved['sample_rng']),
        initial_fixed=initial,final_fixed=fixed_metrics(model,data,device),history=history))
    atomic_json(folder/'training-complete.json',{name:digest(folder/name) for name in ['checkpoint.pt','training.json','training.jsonl']})


def run(manifest,out):
    m=read(manifest); verify_manifest(m); out.mkdir(parents=True,exist_ok=False)
    atomic_json(out/'manifest.json',m)
    for name,sha in m['source_hashes'].items():
        dest=out/'source'/name; dest.parent.mkdir(parents=True,exist_ok=True); shutil.copyfile(ROOT/name,dest)
        assert digest(dest)==sha
    torch.set_num_threads(4); torch.use_deterministic_algorithms(True)
    torch.backends.cuda.matmul.allow_tf32=False; torch.backends.cudnn.allow_tf32=False
    atomic_json(out/'environment.json',dict(python=platform.python_version(),executable=sys.executable,
        python_executable_sha256=digest(sys.executable),torch=str(torch.__version__),numpy=np.__version__,
        gpu=torch.cuda.get_device_name(),deterministic_algorithms=True,tf32=False,cublas=os.getenv('CUBLAS_WORKSPACE_CONFIG')))
    records=[]; exact=[]
    for index,pair in enumerate(m['pairs']):
        c=pair['config']; root=out/identity(c); root.mkdir()
        data=torch.load(ROOT/pair['pool'],weights_only=True); independent=torch.load(ROOT/pair['independent'],weights_only=True)
        assert same(data,nested_data(c)) and same(independent,nested_data(c,65536,m['independent_seed']))
        assert overlap(data['points'],independent['points'])==0
        atomic_json(root/'data-audit.json',dict(pool_sha256=tensor_hash(data['points'],data['target']),independent_sha256=tensor_hash(independent['points'],independent['target']),overlap=0,exact_historical_pool=True))
        orders={arm['name']:schedule(arm['name'],index) for arm in ARMS}
        torch.save(orders,root/'orders.pt')
        atomic_json(root/'orders.json',dict(seed=700000+index,sha256=digest(root/'orders.pt'),tensors={n:tensor_hash(v) for n,v in orders.items()}))
        rotated=ARMS[index%4:]+ARMS[:index%4]
        for arm in rotated:
            previous=ROOT/pair['checkpoint']
            for end in ENDS:
                folder=root/arm['name']/f'step-{end}'/'attempt-0001'
                stage=time.perf_counter(); train(c,previous,end,folder,data,arm,orders[arm['name']])
                r=measurements(c,folder,m,data,independent)
                r['stage_seconds']=time.perf_counter()-stage
                if arm['name'] in ['dense','canonical']:
                    saved=torch.load(folder/'checkpoint.pt',map_location='cpu',weights_only=True)
                    old=torch.load(ROOT/pair['historical'][arm['name']][str(end)],map_location='cpu',weights_only=True)
                    e=dict(policy=c['policy'],seed=c['seed'],arm=arm['name'],step=end,
                           **{key+'_exact':same(saved[key],old[key]) for key in ['model','optimizer','sample_rng']})
                    exact.append(e); atomic_json(out/'reproduction.json',dict(checkpoints=exact))
                records.append(dict(folder=folder.relative_to(ROOT).as_posix(),**r))
                atomic_json(folder/'metrics.json',r)
                atomic_json(folder/'complete.json',{p.name:digest(p) for p in folder.iterdir() if p.is_file() and p.name!='complete.json' and not p.name.endswith('.tmp')})
                atomic_json(out/'summary.json',dict(runs=records))
                previous=folder/'checkpoint.pt'
                print(json.dumps(dict(pair=f"{c['policy']}:{c['seed']}",arm=arm['name'],step=end,primary=r['primary_gate'],
                    train_seconds=r['training']['seconds'],eval_seconds=r['evaluation_seconds'],completed=len(records),expected=48)),flush=True)
    assert len(records)==48
    verify_manifest(m)
    atomic_json(out/'run-complete.json',dict(checkpoints=48,summary_sha256=digest(out/'summary.json'),reservation_unchanged=True))


def valid_row(r):
    try:
        metrics=[r['independent_fit']['gap']['rmse'],r['full_gap']['regions']['whole_gap']['all_margins']['sign_accuracy']]
        for res in ['192','384']:
            e=r['evaluations'][res]
            if not e['mesh_present'] or not e['reference_resolved']: return False
            metrics.append(e['symmetric_chamfer'])
        return all(isinstance(v,(float,int)) and math.isfinite(v) for v in metrics)
    except (KeyError,TypeError): return False


def qualify(records,exact):
    names=[a['name'] for a in ARMS]
    expected={(p,s,a,end) for p in ['global_narrow','local'] for s in [31,32,33] for a in names for end in ENDS}
    keys=[(r['metadata']['config']['policy'],r['metadata']['config']['seed'],r['training']['arm']['name'],r['metadata']['step']) for r in records]
    complete=set(keys)==expected and len(keys)==48 and all(valid_row(r) for r in records)
    reproduction=len(exact)==24 and all(all(e.get(k) is True for k in ['model_exact','optimizer_exact','sample_rng_exact']) for e in exact)
    result=dict(complete_and_finite=complete,baseline_reproduction=reproduction,arms=[],gate_pass=False)
    if not complete: result['reason']='Incomplete, invalid, unresolved or nonfinite measurements'; return result
    dense=[r for r in records if r['training']['arm']['name']=='dense']
    dense_seconds=sum(r['training']['seconds'] for r in dense)
    for name in names[1:]:
        rows=[r for r in records if r['training']['arm']['name']==name]
        persistent=sum(all(r['primary_gate'] for r in rows if r['metadata']['config']['policy']==p and r['metadata']['config']['seed']==s) for p in ['global_narrow','local'] for s in [31,32,33])
        comparisons=[]
        for end in ENDS:
            a=[r for r in rows if r['metadata']['step']==end]; b=[r for r in dense if r['metadata']['step']==end]
            mean=statistics.mean
            d=dict(step=end,gap_rmse_ratio=mean(r['independent_fit']['gap']['rmse'] for r in a)/mean(r['independent_fit']['gap']['rmse'] for r in b),
                gap_sign_delta=mean(r['full_gap']['regions']['whole_gap']['all_margins']['sign_accuracy'] for r in a)-mean(r['full_gap']['regions']['whole_gap']['all_margins']['sign_accuracy'] for r in b))
            for res in ['192','384']: d['chamfer_ratio_'+res]=mean(r['evaluations'][res]['symmetric_chamfer'] for r in a)/mean(r['evaluations'][res]['symmetric_chamfer'] for r in b)
            d['passes']=d['gap_rmse_ratio']<=1.10 and d['gap_sign_delta']>=-.005 and all(d['chamfer_ratio_'+res]<=1.05 for res in ['192','384'])
            comparisons.append(d)
        ratio=sum(r['training']['seconds'] for r in rows)/dense_seconds
        result['arms'].append(dict(arm=name,persistent_passes=persistent,training_time_ratio=ratio,presentation_ratio=.25,comparisons=comparisons,
            qualifies=persistent==6 and ratio<=.90 and all(d['passes'] for d in comparisons)))
    result['gate_pass']=reproduction and all(d['qualifies'] for d in result['arms'])
    result['reason']='Advance to frozen confirmation' if result['gate_pass'] else ('Invalid baseline reproduction' if not reproduction else 'Order robustness or frozen guardrail failed; stop research')
    return result


def allowance(state):
    if any(not a.get('finished') for a in state['attempts']): raise RuntimeError('Unclosed charged attempt')
    return state['limit_seconds']-sum(a['charged_seconds'] for a in state['attempts'])


def charged(command,batch=None):
    ledger=DEST/'budget.json'; state=read(ledger); remaining=allowance(state)
    if remaining<=15: raise RuntimeError('Budget exhausted')
    if batch is not None:
        batches=[a['batch'] for a in state['attempts'] if a.get('batch') is not None]
        if batch in batches or len(batches)>=state['maximum_batches']: raise RuntimeError('Batch already consumed or maximum reached')
    row=dict(batch=batch,command=command,started_utc=utc(),finished=False)
    state['attempts'].append(row); atomic_json(ledger,state); began=time.perf_counter(); code=-1
    env=dict(os.environ,CUBLAS_WORKSPACE_CONFIG=':4096:8',PYTHONPATH=str(ROOT),PYTHONDONTWRITEBYTECODE='1')
    log=DEST/(f'batch-{batch}-stdout.log' if batch else f'tests-{len(state["attempts"])}.log')
    try:
        with log.open('x',encoding='utf-8') as f:
            process=subprocess.run([sys.executable]+command,cwd=ROOT,env=env,stdout=f,stderr=subprocess.STDOUT,timeout=remaining-5)
            code=process.returncode
    except subprocess.TimeoutExpired: row['timed_out']=True
    finally:
        row.update(finished=True,charged_seconds=time.perf_counter()-began,exit_code=code,finished_utc=utc(),log=log.relative_to(ROOT).as_posix())
        atomic_json(ledger,state)
    print(json.dumps(row),flush=True)
    if code: raise SystemExit(code)


